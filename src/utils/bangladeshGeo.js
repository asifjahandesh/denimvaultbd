// --- Helper Functions ---

/**
 * Returns all 64 districts formatted with label and value
 */
export function getAllDistricts(lang = 'bn') {
  return BANGLADESH_DISTRICTS.map((d) => ({
    id: d.id,
    label: lang === 'bn' ? d.name_bn : d.name_en,
    name_bn: d.name_bn,
    name_en: d.name_en
  }))
}

/**
 * Finds district object by either its ID or BN/EN name
 */
export function findDistrict(districtQuery) {
  if (!districtQuery) return null
  const q = districtQuery.toLowerCase().trim()
  return BANGLADESH_DISTRICTS.find(
    (d) =>
      d.id.toLowerCase() === q ||
      d.name_bn.toLowerCase() === q ||
      d.name_en.toLowerCase() === q
  )
}

/**
 * Returns upazilas for a given district
 */
export function getUpazilasForDistrict(districtQuery, lang = 'bn') {
  const district = findDistrict(districtQuery)
  if (!district) return []
  return district.upazilas.map((u) => ({
    label: lang === 'bn' ? u.name_bn : u.name_en,
    value: lang === 'bn' ? u.name_bn : u.name_en
  }))
}

/**
 * Returns thanas for a given district
 */
export function getThanasForDistrict(districtQuery, lang = 'bn') {
  const district = findDistrict(districtQuery)
  if (!district) return []
  return district.thanas.map((t) => ({
    label: lang === 'bn' ? t.name_bn : t.name_en,
    value: lang === 'bn' ? t.name_bn : t.name_en
  }))
}

/**
 * Checks if a given district is Dhaka (for delivery charge auto-suggestion)
 */
export function isDhakaDistrict(districtQuery) {
  if (!districtQuery) return false
  const q = districtQuery.toLowerCase().trim()
  return q === 'ঢাকা' || q === 'dhaka'
}

/**
 * Formats a clean, standardized delivery address line
 */
export function formatFullAddress({ addressLine, thana, upazila, district, lang = 'bn' }) {
  const parts = []
  if (addressLine && addressLine.trim()) parts.push(addressLine.trim())
  if (thana && thana.trim()) parts.push(lang === 'bn' ? `থানা: ${thana.trim()}` : `Thana: ${thana.trim()}`)
  if (upazila && upazila.trim()) parts.push(lang === 'bn' ? `উপজেলা: ${upazila.trim()}` : `Upazila: ${upazila.trim()}`)
  if (district && district.trim()) parts.push(lang === 'bn' ? `জেলা: ${district.trim()}` : `District: ${district.trim()}`)
  return parts.join(', ')
}
